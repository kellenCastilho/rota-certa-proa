assert.equal((await google(b,'token-google-test',true,later,'2026-10-09T10:08:00Z')).premium,true);
assert.equal((await db.query('select count(*)::int n from entregas')).rows[0].n,1);
assert.equal((await db.query('select enforced from darota_plan_accounts where user_id=$1',[a])).rows[0].enforced,false);
await db.exec('set role authenticated;');
await assert.rejects(db.exec('select * from darota_google_subscriptions;'),/permission denied/);
await assert.rejects(db.exec(`select darota_recompute_premium('${a}');`),/permission denied/);
await assert.rejects(db.exec(`select darota_record_google_subscription('${a}','token-malicioso',false,'SUBSCRIPTION_STATE_ACTIVE',now()+interval '1 year',now());`),/permission denied/);
